  (
    moc_mafs
    LEFT JOIN Main_org_list ON moc_mafs.org_cd = Main_org_list.org_code
  )
  INNER JOIN [mh60-s ddsn list] ON moc_mafs.cur_ti_ddsn = [mh60-s ddsn list].ddsn;
