  moc_mafs.fgc,
  moc_mafs.tec,
  moc_mafs.niin,
  moc_mafs.hof_niin,
  moc_mafs.wc_cd,
  moc_mafs.mcn,
  moc_mafs.cur_ti_ddsn,
  moc_mafs.org_cd,
