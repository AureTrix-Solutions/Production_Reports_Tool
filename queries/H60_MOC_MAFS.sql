  moc_mafs.sys_rsn,
  moc_mafs.unit_price,
  moc_mafs.net_price,
  moc_mafs.act_take_cd,
  moc_mafs.maint_trans_cd,
  moc_mafs.initiated_date,
  moc_mafs.current_status,
  moc_mafs.current_status_date,
  moc_mafs.Maf_age,
  moc_mafs.ty_maf_cd,
  moc_mafs.maint_lv_cd,
  moc_mafs.wrk_pri_cd,
  moc_mafs.proj_cd
